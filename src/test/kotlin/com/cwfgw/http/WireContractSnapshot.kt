/**
 * Renders the wire types reachable from [roots] to the text pinned in `src/test/resources/wire-contract.txt`.
 *
 * One block per type, sorted by name, so one shape change is one hunk however many types embed it.
 * Sealed variants nest under their parent: on the wire they have no identity apart from its discriminator.
 */
private fun renderWireContract(roots: List<SerialDescriptor>): String =
    walkWireTypes(roots)
        .blocks
        .entries
        .sortedBy { it.key.toString() }
        .joinToString("\n\n") { (heading, block) ->
            (listOf(heading.toString()) + block.lines).joinToString("\n")
        } + "\n"

/** Keyed by block heading name, type arguments included. Read off the walk the snapshot renders. */
internal fun wireReachableDescriptors(roots: List<SerialDescriptor>): Map<String, SerialDescriptor> =
    walkWireTypes(roots).blocks.entries.associate { (heading, block) -> heading.serialName to block.descriptor }

/**
 * Every serial name a root reaches, block or not. A class-level `@Serializable(with = ...)` on anything
 * but an enum renders as a primitive, so it gets no block and is reached only as a leaf.
 */
internal fun wireReachableSerialNames(roots: List<SerialDescriptor>): Set<String> {
    val walk = walkWireTypes(roots)
    return walk.blocks.keys.map { it.serialName.substringBefore('<') }.toSet() + walk.leaves
}

private data class BlockHeading(val serialName: String, val kind: String) {
    override fun toString(): String = "$serialName [$kind]"
}

private data class WireBlock(val descriptor: SerialDescriptor, val lines: List<String>)

private class WireWalk(val blocks: Map<BlockHeading, WireBlock>, val leaves: Set<String>)

private fun walkWireTypes(roots: List<SerialDescriptor>): WireWalk {
    val blocks = mutableMapOf<BlockHeading, WireBlock>()
    val leaves = mutableSetOf<String>()
    val queue = ArrayDeque(roots)
    while (queue.isNotEmpty()) {
        val descriptor = queue.removeFirst()
        val heading = blockHeading(descriptor)
        val reachedFromHere = mutableListOf<SerialDescriptor>()
        val body = bodyLines(descriptor, indent = "  ", reach = reachedFromHere::add)
        val existing = blocks.put(heading, WireBlock(descriptor, body))
        // Two different shapes under one heading would silently drop one of them.
        check(existing == null || existing.lines == body) { "two different wire shapes both render as $heading" }
        // Descending only on the first visit is what terminates a cyclic graph.
        if (existing == null) {
            val (blockTypes, leafTypes) = reachedFromHere.partition(::rendersAsBlock)
            queue.addAll(blockTypes)
            leafTypes.mapTo(leaves) { it.serialName.removeSuffix("?") }
        }
    }
    return WireWalk(blocks, leaves)
}

private fun rendersAsBlock(descriptor: SerialDescriptor): Boolean =
    descriptor.kind in setOf(StructureKind.CLASS, StructureKind.OBJECT, SerialKind.ENUM, PolymorphicKind.SEALED) ||
        customSerializedEnum(descriptor) != null

/** A plain enum's serial names, but for one with its own serializer, whatever that serializer writes. */
internal fun wireEnumValues(descriptor: SerialDescriptor): List<String>? =
    if (descriptor.kind == SerialKind.ENUM) {
        descriptor.elementNames()
    } else {
        customSerializedEnum(descriptor)?.let(::encodedConstants)
    }

/**
 * An enum with its own serializer has a primitive descriptor that names none of its values. One whose
 * descriptor names some other class is not found here, and the accounting test reports the enum unreached.
 */
private fun customSerializedEnum(descriptor: SerialDescriptor): Class<*>? =
    if (descriptor.kind is PrimitiveKind) {
        loadedClass(descriptor.serialName.removeSuffix("?"))?.takeIf { it.isEnum }
    } else {
        null
    }

private fun encodedConstants(enumClass: Class<*>): List<String> {
    val encoder = serializer(enumClass)
    return enumClass.enumConstants.map { appJson.encodeToJsonElement(encoder, it).jsonPrimitive.content }
}

private const val SNAPSHOT_HEADER =
    """# The JSON shape of every type in WIRE_TYPES and of every type reachable from one.
# Generated by WireContractSpec; do not hand-edit. A conflict is regenerated, never merged.
#
#     ./gradlew test -x uiBuild -Dkotest.filter.specs='*WireContractSpec'
#     cp build/wire-contract-actual.txt src/test/resources/wire-contract.txt
#
# `-x uiBuild` because :test builds the UI first (processResources bundles ui/dist), and the
# wireContract.generated.ts the same change left stale fails `tsc -b` before the spec runs.
"""

internal fun wireContractSnapshot(roots: List<SerialDescriptor>): String =
    SNAPSHOT_HEADER + "\n" + renderWireContract(roots)

private const val DRIFT_LINE_LIMIT = 60

/** Grouped by type, because which shape changed is what decides whether types.ts changes too. */
internal fun describeDrift(
    recorded: String,
    actual: String,
): String {
    val before = blocksByName(recorded)
    val after = blocksByName(actual)
    val lines =
        (after.keys - before.keys).sorted().map { "new type:     $it" } +
            (before.keys - after.keys).sorted().map { "type gone:    $it" } +
            (before.keys intersect after.keys)
                .sorted()
                .filter { before[it] != after[it] }
                .flatMap { name ->
                    listOf("shape change: $name") + bodyDrift(before[name].orEmpty(), after[name].orEmpty())
                }
    return (lines.take(DRIFT_LINE_LIMIT) + tail(lines.size)).joinToString("\n")
}

private fun tail(total: Int): List<String> =
    if (total > DRIFT_LINE_LIMIT) listOf("… and ${total - DRIFT_LINE_LIMIT} more line(s) of drift") else emptyList()

private fun bodyDrift(
    before: List<String>,
    after: List<String>,
): List<String> {
    val removed = (before - after.toSet()).map { "  -$it" }
    val added = (after - before.toSet()).map { "  +$it" }
    return (removed + added).ifEmpty { listOf("  (element order changed)") }
}

private fun blocksByName(snapshot: String): Map<String, List<String>> =
    snapshot
        .split("\n\n")
        .filterNot { it.isBlank() || it.startsWith("#") }
        .mapNotNull { block ->
            val lines = block.lines().filterNot(String::isBlank)
            lines.firstOrNull()?.let { header -> header to lines.drop(1) }
        }.toMap()

/** Nullability belongs to the element holding a type, so `Golfer` and `Golfer?` are one block. */
private fun blockHeading(descriptor: SerialDescriptor): BlockHeading =
    BlockHeading(serialName = typeReference(descriptor).removeSuffix("?"), kind = kindLabel(descriptor))

private fun bodyLines(
    descriptor: SerialDescriptor,
    indent: String,
    reach: (SerialDescriptor) -> Unit,
): List<String> {
    val enumValues = wireEnumValues(descriptor)
    return when {
        descriptor.isInline -> {
            val wrapped = descriptor.getElementDescriptor(0)
            reachedTypes(wrapped).forEach(reach)
            listOf("$indent${typeReference(wrapped)} [${kindLabel(wrapped)}]")
        }
        enumValues != null -> enumValues.map { "$indent$it" }
        descriptor.kind == PolymorphicKind.SEALED -> sealedBodyLines(descriptor, indent, reach)
        else -> descriptor.elementIndices().map { elementLine(descriptor, it, indent, reach) }
    }
}

private fun sealedBodyLines(
    descriptor: SerialDescriptor,
    indent: String,
    reach: (SerialDescriptor) -> Unit,
): List<String> =
    listOf("${indent}discriminator: ${sealedDiscriminator(descriptor)}") +
        sealedVariants(descriptor).flatMap { variant ->
            listOf("$indent${variant.serialName} [${variant.descriptor.kind}]") +
                bodyLines(variant.descriptor, "$indent  ", reach)
        }

/** A hierarchy's own `@JsonClassDiscriminator` wins over [appJson]'s, exactly as the encoder resolves it. */
internal fun sealedDiscriminator(descriptor: SerialDescriptor): String =
    descriptor.annotations.filterIsInstance<JsonClassDiscriminator>().firstOrNull()?.discriminator
        ?: appJson.configuration.classDiscriminator

/** [serialName] is the discriminator value. */
internal data class SealedVariant(val serialName: String, val descriptor: SerialDescriptor)

/**
 * A sealed descriptor holds a discriminator element and a `Sealed<T>` element whose children are the
 * variants. Sorted, because the discriminator picks the variant, so their order is not a wire fact.
 */
internal fun sealedVariants(descriptor: SerialDescriptor): List<SealedVariant> {
    val holder =
        descriptor
            .elementIndices()
            .map(descriptor::getElementDescriptor)
            .firstOrNull { it.kind == SerialKind.CONTEXTUAL }
            ?: error("${descriptor.serialName} is SEALED but carries no variant descriptor")
    return holder
        .elementIndices()
        .sortedBy(holder::getElementName)
        .map { SealedVariant(holder.getElementName(it), holder.getElementDescriptor(it)) }
}

private fun elementLine(
    descriptor: SerialDescriptor,
    index: Int,
    indent: String,
    reach: (SerialDescriptor) -> Unit,
): String {
    val element = descriptor.getElementDescriptor(index)
    reachedTypes(element).forEach(reach)
    val optional = if (descriptor.isElementOptional(index)) " optional" else ""
    return "$indent${wireElementName(descriptor, index)}: ${typeReference(element)} [${kindLabel(element)}]$optional"
}

/**
 * The JSON key kotlinx writes: [appJson]'s naming strategy, which kotlinx applies to CLASS elements
 * only, an explicit `@SerialName` included. Discriminator and enum values are not keys and stay verbatim.
 */
internal fun wireElementName(
    descriptor: SerialDescriptor,
    index: Int,
): String {
    val name = descriptor.getElementName(index)
    val strategy = appJson.configuration.namingStrategy
    return if (strategy != null && descriptor.kind == StructureKind.CLASS) {
        strategy.serialNameForJson(descriptor, index, name)
    } else {
        name
    }
}

/** Containers render inline at the element that holds them, so what they hold is what is reached. */
private fun reachedTypes(descriptor: SerialDescriptor): List<SerialDescriptor> =
    when (descriptor.kind) {
        StructureKind.LIST, StructureKind.MAP ->
            descriptor.elementIndices().flatMap { reachedTypes(descriptor.getElementDescriptor(it)) }
        // An open hierarchy's variants live in a SerializersModule, which no descriptor exposes, so
        // rendering one would pin a heading and silently miss everything under it.
        SerialKind.CONTEXTUAL, PolymorphicKind.OPEN ->
            error("${descriptor.serialName} is ${descriptor.kind}: the snapshot cannot see its wire shape")
        else -> listOf(descriptor)
    }

/** A value class is its wrapped value on the wire, which a CLASS label would hide. */
private fun kindLabel(descriptor: SerialDescriptor): String =
    if (descriptor.isInline) "INLINE" else descriptor.kind.toString()

private fun typeReference(descriptor: SerialDescriptor): String {
    val base =
        when (descriptor.kind) {
            StructureKind.LIST -> "List<${typeReference(descriptor.getElementDescriptor(0))}>"
            StructureKind.MAP ->
                "Map<${typeReference(descriptor.getElementDescriptor(0))}, " +
                    "${typeReference(descriptor.getElementDescriptor(1))}>"
            else -> descriptor.serialName.removeSuffix("?") + typeArgumentSuffix(descriptor)
        }
    return if (descriptor.isNullable) "$base?" else base
}

/**
 * kotlinx gives every instantiation of a generic class one serial name, so two would collide under one
 * heading. The arguments are recovered by matching the class's field types against the element descriptors.
 */
private fun typeArgumentSuffix(descriptor: SerialDescriptor): String {
    val declaring = declaringClass(descriptor) ?: return ""
    if (declaring.typeParameters.isEmpty()) return ""
    val bound =
        descriptor.elementIndices().fold(emptyMap<String, SerialDescriptor>()) { bindings, index ->
            val field = declaring.declaredFields.firstOrNull { it.name == descriptor.getElementName(index) }
            field?.let { typeVariableBindings(it.genericType, descriptor.getElementDescriptor(index)) + bindings }
                ?: bindings
        }
    val arguments =
        declaring.typeParameters.map { parameter ->
            bound[parameter.name]
                ?: error("${descriptor.serialName}: no element binds type parameter ${parameter.name}")
        }
    return arguments.joinToString(prefix = "<", postfix = ">", transform = ::typeReference)
}

internal fun wireTypeParameterCount(descriptor: SerialDescriptor): Int =
    declaringClass(descriptor)?.typeParameters?.size ?: 0

private fun declaringClass(descriptor: SerialDescriptor): Class<*>? {
    if (descriptor.kind != StructureKind.CLASS || descriptor.isInline) return null
    return loadedClass(descriptor.serialName.removeSuffix("?"))
}

private fun loadedClass(className: String): Class<*>? {
    val loader = WireBlock::class.java.classLoader
    return loader.getResource(className.replace('.', '/') + ".class")?.let { Class.forName(className, false, loader) }
}

private fun typeVariableBindings(
    type: Type,
    descriptor: SerialDescriptor,
): Map<String, SerialDescriptor> =
    when {
        type is TypeVariable<*> -> mapOf(type.name to descriptor)
        type is WildcardType -> type.upperBounds.firstOrNull()?.let { typeVariableBindings(it, descriptor) }.orEmpty()
        type is ParameterizedType && descriptor.kind in setOf(StructureKind.LIST, StructureKind.MAP) ->
            type.actualTypeArguments
                .zip(descriptor.elementIndices().map(descriptor::getElementDescriptor))
                .fold(emptyMap()) { bindings, (argument, element) ->
                    typeVariableBindings(argument, element) + bindings
                }
        else -> emptyMap()
    }

internal fun SerialDescriptor.elementIndices(): List<Int> = (0 until elementsCount).toList()

internal fun SerialDescriptor.elementNames(): List<String> = elementIndices().map(::getElementName)
